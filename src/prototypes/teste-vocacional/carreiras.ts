/**
 * Perfil de referência derivado do código Holland da ocupação (O*NET):
 * 1ª letra 88 · 2ª 70 · 3ª 56 · demais 24 (escala 0–100).
 */
export function perfilDe(codigo: string): Record<Dim, number> {
  const p: Record<Dim, number> = { R: 24, I: 24, A: 24, S: 24, E: 24, C: 24 }
  ;[88, 70, 56].forEach((v, i) => codigo[i] && (p[codigo[i] as Dim] = v))
  return p
}

const ctx = (s: string): Contexto => {
  const m = (c: string) => (c === 'a' ? 'a' : c === 'b' ? 'b' : 'ambos') as 'a' | 'b' | 'ambos'
  return { P01: m(s[0]), P02: m(s[1]), P03: m(s[2]), P04: m(s[3]), P05: m(s[4]), P06: m(s[5]) }
}

