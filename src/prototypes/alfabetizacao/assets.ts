/** URL de um asset extraído das referências. */
export const asset = (name: string) => `./alfa/${name}.webp`

type Vars = React.CSSProperties & Record<`--${string}`, number | string>

/** Caixa no layout retrato (quadro 390×844): [x, y, largura, altura?]. */
export type PBox = [number, number, number, number?]

function portrait(p?: PBox): Vars {
  if (!p) return {}
  const v: Vars = { '--px': p[0], '--py': p[1], '--pw': p[2] }
  if (p[3] !== undefined) v['--ph'] = p[3]
  return v
}

/**
 * Variáveis CSS para posicionar um recorte onde ele está na referência (quadro paisagem 1672×941).
 * `p` define a caixa no layout retrato; a altura do retrato é deduzida da proporção do recorte.
 */
export function place(name: string, p?: PBox): Vars {
  const m = META[name]
  if (!m) return portrait(p)
  const pb: PBox | undefined = p && (p[3] === undefined ? [p[0], p[1], p[2], Math.round((p[2] * m.h) / m.w)] : p)
  return { '--x': m.x ?? 0, '--y': m.y ?? 0, '--w': m.w, '--h': m.h, ...portrait(pb) }
}

/** Variáveis CSS para uma caixa qualquer em coordenadas de design (x, y, largura, altura) + retrato opcional. */
export function box(x: number, y: number, w: number, h?: number, p?: PBox): Vars {
  const v: Vars = { '--x': x, '--y': y, '--w': w }
  if (h !== undefined) v['--h'] = h
  return { ...v, ...portrait(p) }
}
